
USE DATABASE ECOMMERCE_DB;
USE SCHEMA RAW;

-- Customer source data
CREATE TABLE IF NOT EXISTS CUSTOMERS (
    CUSTOMER_ID VARCHAR,
    NAME         VARCHAR,
    EMAIL        VARCHAR,
    CITY         VARCHAR,
    SIGNUP_DATE  VARCHAR
);

-- Product source data
CREATE TABLE IF NOT EXISTS PRODUCTS (
    PRODUCT_ID   VARCHAR,
    PRODUCT_NAME VARCHAR,
    CATEGORY     VARCHAR,
    PRICE        VARCHAR
);

-- Order source data
CREATE TABLE IF NOT EXISTS ORDERS (
    ORDER_ID     VARCHAR,
    CUSTOMER_ID  VARCHAR,
    PRODUCT_ID   VARCHAR,
    QUANTITY     VARCHAR,
    ORDER_DATE   VARCHAR,
    ORDER_STATUS VARCHAR
);


