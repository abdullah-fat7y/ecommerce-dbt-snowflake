USE DATABASE ECOMMERCE_DB;
USE SCHEMA STAGING_STAGING;

SHOW TABLES;
SHOW VIEWS;

SELECT *
FROM ECOMMERCE_DB.STAGING_STAGING.STG_CUSTOMERS
LIMIT 10;

SELECT *
FROM ECOMMERCE_DB.STAGING_STAGING.STG_PRODUCTS
LIMIT 10;

SELECT *
FROM ECOMMERCE_DB.STAGING_STAGING.STG_ORDERS
LIMIT 10;





SELECT 'STG_CUSTOMERS' AS MODEL, COUNT(*) AS ROW_COUNT
FROM ECOMMERCE_DB.STAGING_STAGING.STG_CUSTOMERS

UNION ALL

SELECT 'STG_PRODUCTS', COUNT(*)
FROM ECOMMERCE_DB.STAGING_STAGING.STG_PRODUCTS

UNION ALL

SELECT 'STG_ORDERS', COUNT(*)
FROM ECOMMERCE_DB.STAGING_STAGING.STG_ORDERS;

DESCRIBE VIEW ECOMMERCE_DB.STAGING_STAGING.STG_ORDERS;