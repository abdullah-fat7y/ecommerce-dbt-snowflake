SELECT
    o.ORDER_ID,
    o.CUSTOMER_ID
FROM ECOMMERCE_DB.STAGING_STAGING.STG_ORDERS AS o
LEFT JOIN ECOMMERCE_DB.STAGING_STAGING.STG_CUSTOMERS AS c
    ON o.CUSTOMER_ID = c.CUSTOMER_ID
WHERE c.CUSTOMER_ID IS NULL;


SELECT
    o.ORDER_ID,
    o.PRODUCT_ID
FROM ECOMMERCE_DB.STAGING_STAGING.STG_ORDERS AS o
